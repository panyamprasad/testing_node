//---> What is Angular Material?
//      -> 1. Angular Material is a UI Component Library for angular applications.
//      -> 2. It is developed and maintained by the angular team and follows Google's Material design guidelines.
//      -> 3. It will provide the ready made UI components such as 
//              -> buttons, 
//              -> forms, 
//              -> tables, 
//              -> dialogs,
//              -> menus, 
//              -> cards
//              -> Date pickers and more.

//---> What do we use Angular Material?
//      -> Without angular Material we have to create each and everything from scratch.
//      -> We have to use HTML, CSS and plain JavaScript should we build all the styles.
//      -> Using the Angular Material it will provide Pre-build UI components.
//      -> Consistent design across the application.
//      -> Responsive layouts for mobile & desktop.
//      -> Faster development with less code.

//---> When should we use Angular Material?
//      -> If we need Professional UI design Quickly will use the Angular Material.
//      -> Instead of creating buttons, labels, dialogs etc from scratch.
//      -> Ex: Login Page, Dashboard, registration.
//      -> Many internal Business applications are use Angular Material because it provide clean and consistent UI.
//          -> Ex: Employee Management System, Banking Dashboard, Admin Panel.. etc.

//---> Features of Angular Material?
//      -> Mat-button, mat-card, mat-table, mat-dialog, mat-form-field, mat-datepicker, mat-menu, mat-toolbar etc...