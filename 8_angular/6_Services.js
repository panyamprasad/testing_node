//---> 1. What is Angular Services?
//      -> 1. A service in Angular is a reusable typeScript class.
//      -> 2. It contains business logic, api calls, shared Data, authentication, logging, caching etc.
//      -> 3. Services are injected into the components using the Dependency Injection.
//      -> 4. Uses:
//              -> Without Services unable to maintain, testing and debugging the code.
//              -> Using services, we can reusable the code.
//              -> Easy to testing, clean architecture and better maintainability.
//
//--------------------------------------------------
//
//---> 2. What is Dependency Injection?
//      -> 1. Dependency Injection is a design pattern.
//      -> 2. Angular automatically creates and injects the required dependencies into components and services.
//
//--------------------------------------------------
//
//---> 3. What is Singleton Service in Angular?
//      -> 1. Singleton service is a service, the angular creates only one instance and shares it across the application.
//      -> 2. When a service is provided using ProvidedIn: 'root', Angular creates a single shared service.
//      -> 3. That can be accessed by all components and other services.
//
//--------------------------------------------------
